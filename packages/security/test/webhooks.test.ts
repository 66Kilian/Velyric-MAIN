import { createHash, generateKeyPairSync, randomBytes, sign } from 'node:crypto';
import Stripe from 'stripe';
import twilio from 'twilio';
import { describe, expect, it } from 'vitest';
import {
  computeStandardWebhookSignature,
  computeTwilioSignature,
  stripeSignatureHeader,
  verifyStandardWebhook,
  verifyStripeSignature,
  verifyTelnyxSignature,
  verifyTwilioSignature,
  WebhookVerificationError,
} from '../src/webhooks.js';

function codeOf(fn: () => void): string | undefined {
  try {
    fn();
    return undefined;
  } catch (error) {
    return error instanceof WebhookVerificationError ? error.code : 'OTHER';
  }
}

describe('Stripe signatures', () => {
  const stripe = new Stripe('sk_test_velyric_unit');
  const secret = 'whsec_test_velyric_signing_secret';
  const payload = JSON.stringify({ id: 'evt_1', object: 'event', type: 'invoice.paid' });
  const now = Math.floor(Date.now() / 1000);

  it('accepts headers generated by the official Stripe SDK', () => {
    const header = stripe.webhooks.generateTestHeaderString({ payload, secret, timestamp: now });
    expect(() => {
      verifyStripeSignature(payload, header, [secret], { nowSeconds: now });
    }).not.toThrow();
  });

  it('produces headers the official Stripe SDK accepts', () => {
    const event = stripe.webhooks.constructEvent(
      payload,
      stripeSignatureHeader(payload, secret, now),
      secret,
    );
    expect(event.id).toBe('evt_1');
  });

  it('supports secret rotation and rejects tampering, bad headers and stale timestamps', () => {
    const header = stripeSignatureHeader(payload, secret, now);
    expect(
      codeOf(() => {
        verifyStripeSignature(payload, header, ['whsec_old', secret], { nowSeconds: now });
      }),
    ).toBeUndefined();
    expect(
      codeOf(() => {
        verifyStripeSignature(`${payload} `, header, [secret], { nowSeconds: now });
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyStripeSignature(payload, undefined, [secret]);
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyStripeSignature(payload, 't=abc,v1=zz', [secret]);
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyStripeSignature(payload, header, [secret], { nowSeconds: now + 301 });
      }),
    ).toBe('WEBHOOK_TIMESTAMP_OUT_OF_TOLERANCE');
  });
});

describe('Telnyx Ed25519 signatures', () => {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const rawPublicKey = publicKey
    .export({ format: 'der', type: 'spki' })
    .subarray(-32)
    .toString('base64');
  const payload = '{"data":{"event_type":"call.initiated"}}';
  const now = Math.floor(Date.now() / 1000);
  const timestamp = String(now);
  const signature = sign(null, Buffer.from(`${timestamp}|${payload}`), privateKey).toString(
    'base64',
  );

  it('verifies authentic payloads', () => {
    expect(() => {
      verifyTelnyxSignature(payload, signature, timestamp, rawPublicKey, { nowSeconds: now });
    }).not.toThrow();
  });

  it('rejects tampering, foreign keys, missing headers and replayed timestamps', () => {
    const other = generateKeyPairSync('ed25519')
      .publicKey.export({ format: 'der', type: 'spki' })
      .subarray(-32)
      .toString('base64');
    expect(
      codeOf(() => {
        verifyTelnyxSignature(`${payload}x`, signature, timestamp, rawPublicKey, {
          nowSeconds: now,
        });
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyTelnyxSignature(payload, signature, timestamp, other, { nowSeconds: now });
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyTelnyxSignature(payload, undefined, timestamp, rawPublicKey);
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyTelnyxSignature(payload, signature, timestamp, rawPublicKey, {
          nowSeconds: now + 3600,
        });
      }),
    ).toBe('WEBHOOK_TIMESTAMP_OUT_OF_TOLERANCE');
  });
});

describe('Twilio signatures', () => {
  const authToken = randomBytes(16).toString('hex');
  const url = 'https://api.velyric.test/v1/webhooks/providers/twilio?tenant=abc';
  const params = {
    CallSid: 'CA1234567890ABCDE',
    Caller: '+12349013030',
    Digits: '1234',
    From: '+12349013030',
    To: '+18005551212',
  };

  it('matches the official Twilio SDK for form-encoded requests', () => {
    const signature = computeTwilioSignature(url, params, authToken);
    expect(twilio.validateRequest(authToken, signature, url, params)).toBe(true);
    expect(() => {
      verifyTwilioSignature(url, params, signature, authToken);
    }).not.toThrow();
    expect(
      codeOf(() => {
        verifyTwilioSignature(url, { ...params, Digits: '9' }, signature, authToken);
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
  });

  it('validates JSON bodies through bodySHA256 like the official SDK', () => {
    const body = '{"CallSid":"CA1"}';
    const bodyHash = sha256HexOf(body);
    const jsonUrl = `https://api.velyric.test/v1/webhooks/providers/twilio?bodySHA256=${bodyHash}`;
    const signature = computeTwilioSignature(jsonUrl, {}, authToken);
    expect(twilio.validateRequestWithBody(authToken, signature, jsonUrl, body)).toBe(true);
    expect(() => {
      verifyTwilioSignature(jsonUrl, {}, signature, authToken, body);
    }).not.toThrow();
    expect(
      codeOf(() => {
        verifyTwilioSignature(jsonUrl, {}, signature, authToken, '{"CallSid":"CA2"}');
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
  });
});

function sha256HexOf(body: string): string {
  return createHash('sha256').update(body, 'utf8').digest('hex');
}

describe('Standard Webhooks (OpenAI) signatures', () => {
  const secret = `whsec_${randomBytes(32).toString('base64')}`;
  const payload = '{"type":"realtime.call.incoming"}';
  const now = Math.floor(Date.now() / 1000);
  const id = 'wh_01J8Z';

  it('verifies signatures, including headers carrying several versions', () => {
    const signature = computeStandardWebhookSignature(payload, id, now, secret);
    expect(() => {
      verifyStandardWebhook(
        payload,
        { id, timestamp: String(now), signature: `v1,AAAA ${signature}` },
        [secret],
        { nowSeconds: now },
      );
    }).not.toThrow();
  });

  it('rejects wrong secrets, missing headers and stale timestamps', () => {
    const signature = computeStandardWebhookSignature(payload, id, now, secret);
    const otherSecret = `whsec_${randomBytes(32).toString('base64')}`;
    expect(
      codeOf(() => {
        verifyStandardWebhook(payload, { id, timestamp: String(now), signature }, [otherSecret], {
          nowSeconds: now,
        });
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyStandardWebhook(payload, { id: undefined, timestamp: String(now), signature }, [
          secret,
        ]);
      }),
    ).toBe('WEBHOOK_SIGNATURE_INVALID');
    expect(
      codeOf(() => {
        verifyStandardWebhook(payload, { id, timestamp: String(now), signature }, [secret], {
          nowSeconds: now + 600,
        });
      }),
    ).toBe('WEBHOOK_TIMESTAMP_OUT_OF_TOLERANCE');
  });
});
