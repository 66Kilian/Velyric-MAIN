export interface ApiErrorEnvelope {
  readonly code: ApiErrorCode;
  readonly message_key: string;
  readonly trace_id: string;
  readonly details?: Readonly<Record<string, unknown>>;
}

export function apiErrorMessageKey(code: ApiErrorCode): string {
  return `errors.${code.toLowerCase()}`;
}

export function apiErrorHttpStatus(code: ApiErrorCode): number {
  return API_ERROR_HTTP_STATUS[code];
}

export function createApiErrorEnvelope(
  code: ApiErrorCode,
  traceId: string,
  details?: Readonly<Record<string, unknown>>,
): ApiErrorEnvelope {
  const base = { code, message_key: apiErrorMessageKey(code), trace_id: traceId };
  return details === undefined ? base : { ...base, details };
}
