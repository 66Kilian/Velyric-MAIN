export function enumConstraintName(binding: EnumColumnBinding): string {
  return `${binding.table}_${binding.column}_check`;
}

function quoteLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

export function enumCheckExpression(binding: EnumColumnBinding, values: readonly string[]): string {
  const list = values.map(quoteLiteral).join(', ');
  return binding.array === true
    ? `${binding.column} <@ ARRAY[${list}]::text[]`
    : `${binding.column} IN (${list})`;
}
